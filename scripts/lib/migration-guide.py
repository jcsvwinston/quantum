#!/usr/bin/env python3
"""migration-guide.py — el generador de la guía de migración al 2.0 (A12 M0-E, borrador).

Una entrada por aviso de deprecación `active` de los tres productos: lee
`<root>/{quark,nucleus,orbit}/docs/deprecations/DEP-*.md` —la cabecera
(ID, Status, la viñeta de ventana «Earliest removal | Behaviour flip |
Earliest change», Scope) y las secciones que todo aviso lleva (Summary,
Migration path, Detection o Migration Assistant, What breaks if this is
ignored)— y escribe UNA guía en inglés agrupada por producto, con una
tabla de cabecera (producto, aviso, qué cambia, cuándo) y, por aviso, lo
que el lector necesita para migrar. Nada se redacta aquí: el texto es el
de los avisos, que son la fuente (QADR-0003); si un aviso dice algo mal,
se corrige el aviso y se regenera.

Uso:
  python3 scripts/lib/migration-guide.py                      # los submódulos al pin
  python3 scripts/lib/migration-guide.py --root ~/GolandProjects --out docs/planes/guia-migracion-2.0.md
  python3 scripts/lib/migration-guide.py --check              # EXIT=1 si la salida difiere del fichero

Borrador: dónde vive la guía publicada (el sitio del paraguas, bajo
/migration/2.0) y cómo la vigila un guard lo decide `M1`. Lee la rama que
cada checkout tenga: sobre los submódulos al pin da los avisos que el set
certifica (23 en 1.42.0: los siete de quark de `M0-Q` siguen en su `main`);
sobre una rama `dry-run/2.0` da cero, porque allí los avisos ya están
`completed`/`removed`.
"""
import argparse, pathlib, re, sys

PRODUCTS = ("quark", "nucleus", "orbit")
WINDOW_KEYS = ("Earliest removal", "Behaviour flip", "Earliest change")
SECTIONS = {
    "summary": ("Summary",),
    "change": ("What changes at 2.0",),
    "migration": ("Migration path", "Migration Path"),
    "detection": ("Detection", "Migration Assistant"),
    "breaks": ("What breaks if this is ignored",),
}


def header_bullets(text):
    """Las viñetas anteriores a la primera sección `## `, unidas (una viñeta
    partida en varias líneas va sangrada), igual que las lee el guard."""
    out, acc = [], None
    for line in text.splitlines():
        if line.startswith("## "):
            break
        if line.startswith("# "):
            continue
        if line.startswith("- "):
            if acc is not None:
                out.append(acc)
            acc = line[2:].strip()
        elif acc is not None and line[:1].isspace() and line.strip():
            acc += " " + line.strip()
        elif acc is not None:
            out.append(acc); acc = None
    if acc is not None:
        out.append(acc)
    return out


def section(text, names):
    for name in names:
        m = re.search(r"^## " + re.escape(name) + r"\s*$(.*?)(?=^## |\Z)", text, re.M | re.S)
        if m:
            return m.group(1).strip("\n")
    return ""


def parse(path):
    text = path.read_text(encoding="utf-8")
    title = next((l[2:].strip() for l in text.splitlines() if l.startswith("# ")), path.stem)
    head = {}
    for b in header_bullets(text):
        k, _, v = b.partition(":")
        head[k.strip()] = v.strip()
    status = head.get("Status", "").strip("`")
    window_key = next((k for k in WINDOW_KEYS if k in head), None)
    window = head.get(window_key, "") if window_key else ""
    mver = re.search(r"v\d+\.\d+\.\d+", window)
    mdate = re.search(r"no earlier than `?(\d{4}-\d{2}-\d{2})", window)
    return {
        "id": head.get("ID", "").strip("`"),
        "title": title,
        "status": status,
        "kind": "removal" if window_key == "Earliest removal" else "change" if window_key else "unknown",
        "version": mver.group(0) if mver else "",
        "date": mdate.group(1) if mdate else "",
        "scope": head.get("Scope", "").strip("`"),
        "sections": {k: section(text, names) for k, names in SECTIONS.items()},
        "file": path,
    }


def render(root, notices_by_product):
    out = ["# Migrating to the 2.0 major of the Quantum suite", "",
           "<!-- Generated by scripts/lib/migration-guide.py from docs/deprecations/ of each product. Do not edit: fix the notice and regenerate. -->", "",
           "One major moves the three products together (QADR-0002), and it retires or",
           "changes only what a deprecation notice announced with a window of at least",
           "90 days. This guide has one entry per active notice, in the words of the",
           "notice itself: what changes, how to stay or move, how to detect that you",
           "rely on it, and what breaks if you do nothing.", "",
           "| Product | Notice | What changes at 2.0 | Kind | Not before |", "|---|---|---|---|---|"]
    for prod in PRODUCTS:
        for n in notices_by_product.get(prod, []):
            short = n["title"].split(":", 1)[-1].strip()
            out.append(f"| {prod} | `{n['id']}` | {short} | {n['kind']} | {n['date'] or '—'} |")
    for prod in PRODUCTS:
        ns = notices_by_product.get(prod, [])
        if not ns:
            continue
        out += ["", f"## {prod}", ""]
        for n in ns:
            out += [f"### {n['id']} — {n['title'].split(':', 1)[-1].strip()}", "",
                    f"*{n['kind']} · scope `{n['scope'] or '—'}` · {n['version'] or 'v2.0.0'}, no earlier than {n['date'] or 'TBD'} · source: `{prod}/docs/deprecations/{n['file'].name}`*", ""]
            s = n["sections"]
            for key, heading in (("summary", "What changes"), ("change", "At 2.0"), ("migration", "How to migrate"),
                                 ("detection", "How to tell you rely on it"), ("breaks", "What breaks if ignored")):
                if s.get(key):
                    out += [f"**{heading}**", "", s[key], ""]
    return "\n".join(out).rstrip("\n") + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=".", help="directorio con quark/, nucleus/ y orbit/ (default: los submódulos)")
    ap.add_argument("--out", default="docs/planes/guia-migracion-2.0.md")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    root = pathlib.Path(a.root).expanduser()
    by = {}
    for prod in PRODUCTS:
        d = root / prod / "docs" / "deprecations"
        if not d.is_dir():
            print(f"AVISO: {d} no existe (orbit no tenía registro hasta 1.42.0)", file=sys.stderr)
            continue
        ns = [parse(p) for p in sorted(d.glob("DEP-*.md"))]
        by[prod] = [n for n in ns if n["status"] == "active"]
    text = render(root, by)
    total = sum(len(v) for v in by.values())
    if a.check:
        cur = pathlib.Path(a.out).read_text(encoding="utf-8") if pathlib.Path(a.out).exists() else ""
        if cur != text:
            print(f"FAIL: {a.out} no es lo que generan los avisos ({total} activos); regenera: python3 scripts/lib/migration-guide.py --root {a.root} --out {a.out}", file=sys.stderr)
            return 1
        print(f"OK: {a.out} al día ({total} avisos activos)")
        return 0
    pathlib.Path(a.out).write_text(text, encoding="utf-8")
    print(f"escrito {a.out}: {total} avisos activos (" + ", ".join(f"{p} {len(by.get(p, []))}" for p in PRODUCTS) + ")")
    return 0


if __name__ == "__main__":
    sys.exit(main())
