def rd(rel):
    path = os.path.join(ROOT, rel)
    if not os.path.isfile(path):
        raise SourceError(f'falta {rel} — sin la fuente no hay página que generar (¿submódulos sin inicializar?)')
    with open(path, encoding='utf-8') as f:
        return f.read()


