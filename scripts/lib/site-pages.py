CATALOG_DIR = 'nucleus/internal/knownproviders'
GO_TOKEN = re.compile(r'''
    (?P<nl>\n) | (?P<ws>[ \t\r\f]+) | (?P<lc>//[^\n]*) | (?P<bc>/\*.*?\*/) |
    (?P<raw>`[^`]*`) | (?P<str>"(?:\\.|[^"\\\n])*") | (?P<rune>'(?:\\.|[^'\\\n])+') |
    (?P<num>\.?\d[\w.]*) | (?P<id>[A-Za-z_]\w*) |
    (?P<op>\.\.\.|:=|<-|&&|\|\||==|!=|<=|>=|<<|>>|[{}()\[\],:;.=+\-*/&|<>!^%~])
''', re.S | re.X)
GO_ESC = {'n': '\n', 't': '\t', 'r': '\r', '"': '"', '\\': '\\', "'": "'", 'a': '\a',
          'b': '\b', 'f': '\f', 'v': '\v'}


class GoParseError(SourceError):
    pass


def go_string(lit):
    if lit.startswith('`'):
        return lit[1:-1].replace('\r', '')
    body, out, i = lit[1:-1], [], 0
    while i < len(body):
        c = body[i]
        if c != '\\':
            out.append(c)
            i += 1
            continue
        e = body[i + 1]
        if e in GO_ESC:
            out.append(GO_ESC[e])
            i += 2
        elif e in 'uU':
            w = 4 if e == 'u' else 8
            out.append(chr(int(body[i + 2:i + 2 + w], 16)))
            i += 2 + w
        elif e == 'x':
            out.append(chr(int(body[i + 2:i + 4], 16)))
            i += 4
        else:
            raise ValueError(f'escape \\{e}')
    return ''.join(out)


class GoFile:
    """Lo justo de Go para leer una tabla de literales: tokens, constantes de
    cadena, structs y los `var` cuyo valor es un literal compuesto."""

    def __init__(self, path, text):
        self.path = path
        self.toks = []
        line, pos = 1, 0
        while pos < len(text):
            m = GO_TOKEN.match(text, pos)
            if not m:
                raise GoParseError(f'{path}:{line}: no sé leer «{text[pos:pos + 20]}»')
            kind, val = m.lastgroup, m.group()
            if kind in ('nl',) or (kind == 'bc' and '\n' in val):
                self.toks.append(('nl', '\n', line))
            elif kind not in ('ws', 'lc', 'bc'):
                self.toks.append((kind, val, line))
            line += val.count('\n')
            pos = m.end()
        self.toks.append(('eof', '', line))
        self.i = 0

    # -- navegación
    def peek(self, skip_nl=True, k=0):
        j = self.i
        while True:
            if skip_nl:
                while self.toks[j][0] == 'nl':
                    j += 1
            if k == 0 or self.toks[j][0] == 'eof':
                return self.toks[j]
            k -= 1
            j += 1

    def next(self, skip_nl=True):
        if skip_nl:
            while self.toks[self.i][0] == 'nl':
                self.i += 1
        t = self.toks[self.i]
        self.i += 1
        return t

    def expect(self, val):
        t = self.next()
        if t[1] != val:
            self.fail(t, f'esperaba «{val}»')
        return t

    def fail(self, tok, why):
        raise GoParseError(f'{self.path}:{tok[2]}: {why}, encontré «{tok[1]}» — '
                           'la tabla del catálogo cambió de forma; amplía el lector de scripts/lib/site-pages.py')

    def skip_balanced(self):
        """Salta desde un ( [ o { hasta su cierre."""
        pairs = {'(': ')', '[': ']', '{': '}'}
        t = self.next()
        stack = [pairs[t[1]]]
        while stack:
            t = self.next(skip_nl=False)
            if t[0] == 'eof':
                self.fail(t, 'fichero acabado dentro de un bloque')
            if t[0] == 'op' and t[1] in pairs:
                stack.append(pairs[t[1]])
            elif t[0] == 'op' and t[1] == stack[-1]:
                stack.pop()

    def skip_statement(self):
        """Salta hasta el final de la declaración (salto de línea a profundidad 0)."""
        while True:
            t = self.peek(skip_nl=False)
            if t[0] in ('nl', 'eof') or t[1] in (';', ')'):
                if t[0] == 'nl' or t[1] == ';':
                    self.next(skip_nl=False)
                return
            if t[0] == 'op' and t[1] in '([{':
                self.skip_balanced()
            else:
                self.next(skip_nl=False)

    # -- tipos
    def parse_type(self):
        t = self.next()
        if t[1] == '*':
            return ('ptr', self.parse_type())
        if t[1] == '[':
            if self.peek()[1] == ']':
                self.next()
                return ('slice', self.parse_type())
            while self.next()[1] != ']':
                pass
            return ('array', self.parse_type())
        if t[1] == 'map':
            self.expect('[')
            k = self.parse_type()
            self.expect(']')
            return ('map', k, self.parse_type())
        if t[1] in ('struct', 'interface', 'func'):
            if self.peek()[1] == '(':
                self.skip_balanced()
            if self.peek()[1] == '{':
                self.skip_balanced()
            return ('other', t[1])
        if t[0] == 'id':
            name = t[1]
            if self.peek()[1] == '.' and self.peek(k=1)[0] == 'id':
                self.next()
                name += '.' + self.next()[1]
            return ('named', name)
        self.fail(t, 'esperaba un tipo')


def go_scan(files):
    """Pasada 1: constantes de cadena, structs (con sus campos) y alias de tipo."""
    consts, structs, aliases = {}, {}, {}
    for g in files:
        g.i = 0
        while g.peek()[0] != 'eof':
            t = g.next()
            if t[0] != 'id' or t[1] not in ('const', 'type', 'var', 'func', 'import', 'package'):
                continue
            if t[1] == 'const':
                specs = []
                if g.peek()[1] == '(':
                    g.next()
                    while g.peek()[1] != ')':
                        specs.append(go_spec_tokens(g))
                    g.next()
                else:
                    specs.append(go_spec_tokens(g))
                for spec in specs:
                    go_const_spec(spec, consts)
            elif t[1] == 'type':
                decls = []
                if g.peek()[1] == '(':
                    g.next()
                    while g.peek()[1] != ')':
                        decls.append(g.next())
                        go_type_decl(g, decls[-1], structs, aliases)
                    g.next()
                else:
                    go_type_decl(g, g.next(), structs, aliases)
            elif t[1] == 'func':
                # la firma y el cuerpo: hasta la llave que abre el cuerpo
                while g.peek()[1] != '{' and g.peek()[0] != 'eof':
                    if g.peek()[1] in '([':
                        g.skip_balanced()
                    else:
                        g.next()
                if g.peek()[1] == '{':
                    g.skip_balanced()
            elif t[1] in ('import', 'var'):
                if g.peek()[1] == '(':
                    g.skip_balanced()
                else:
                    g.skip_statement()
    return consts, structs, aliases


def go_spec_tokens(g):
    """Los tokens de una especificación de const, hasta el salto de línea."""
    while g.peek(skip_nl=False)[0] == 'nl':
        g.next(skip_nl=False)
    toks, depth = [], 0
    while True:
        t = g.peek(skip_nl=False)
        if t[0] == 'eof' or (depth == 0 and (t[0] == 'nl' or t[1] == ';' or t[1] == ')')):
            if t[0] == 'nl' or t[1] == ';':
                g.next(skip_nl=False)
            return toks
        g.next(skip_nl=False)
        if t[1] in '([{':
            depth += 1
        elif t[1] in ')]}':
            depth -= 1
        if t[0] != 'nl':
            toks.append(t)


def go_const_spec(toks, consts):
    """NOMBRE [Tipo] = expresión de cadena; lo demás (iota, números) no interesa."""
    if '=' not in [t[1] for t in toks] or toks[0][0] != 'id':
        return
    eq = [t[1] for t in toks].index('=')
    names = [t[1] for t in toks[:eq] if t[0] == 'id']
    if len(names) > 2 or (len(names) == 2 and toks[1][1] == ','):
        return  # varias constantes en una línea: no hay ninguna de cadena así en la tabla
    val, ok = '', True
    rest = toks[eq + 1:]
    for k, t in enumerate(rest):
        if k % 2 == 1:
            ok = ok and t[1] == '+'
        elif t[0] in ('str', 'raw'):
            val += go_string(t[1])
        elif t[0] == 'id' and t[1] in consts:
            val += consts[t[1]]
        else:
            ok = False
    if ok and rest:
        consts[names[0]] = val


def go_type_decl(g, name_tok, structs, aliases):
    if g.peek()[1] == '=':
        g.next()
        aliases[name_tok[1]] = g.parse_type()
        return
    if g.peek()[1] == '[':  # parámetros de tipo
        g.skip_balanced()
    if g.peek()[1] == 'struct':
        g.next()
        g.expect('{')
        fields, at_line_start, depth = [], True, 0
        while True:
            t = g.next(skip_nl=False)
            if t[0] == 'eof':
                g.fail(t, 'struct sin cerrar')
            if t[0] == 'nl' or t[1] == ';':
                at_line_start = True
                continue
            if t[1] in '([{':
                depth += 1
            elif t[1] in ')]':
                depth -= 1
            elif t[1] == '}':
                if depth == 0:
                    break
                depth -= 1
            if at_line_start and depth == 0 and t[0] == 'id':
                fields.append(t[1])
            at_line_start = False
        structs[name_tok[1]] = fields
    else:
        typ = g.parse_type()
        if typ[0] == 'other' and g.peek()[1] == '{':
            g.skip_balanced()


def go_value(g, typ, ctx):
    """Un valor de campo de la tabla: cadenas (con + y constantes), bool, nil,
    números, []string{...} y literales de struct anidados."""
    t = g.peek()
    if t[1] == '&':
        g.next()
        return go_value(g, ('ptr', typ[1] if typ and typ[0] == 'ptr' else typ), ctx)
    if t[1] == '{':  # elemento con el tipo elidido
        elem = typ[1] if typ and typ[0] == 'ptr' else typ
        return go_composite(g, elem, ctx)
    if t[1] in ('[', 'map') or (t[0] == 'id' and g.peek(k=1)[1] in ('{', '.') and t[1] not in ctx['consts']):
        lit_type = g.parse_type()
        return go_composite(g, lit_type, ctx)
    if t[0] in ('str', 'raw') or (t[0] == 'id' and t[1] in ctx['consts']):
        s = ''
        while True:
            t = g.next()
            if t[0] in ('str', 'raw'):
                s += go_string(t[1])
            elif t[0] == 'id' and t[1] in ctx['consts']:
                s += ctx['consts'][t[1]]
            else:
                g.fail(t, 'esperaba una cadena o una constante de cadena')
            if g.peek()[1] != '+':
                return s
            g.next()
    if t[0] == 'id' and t[1] in ('true', 'false'):
        g.next()
        return t[1] == 'true'
    if t[0] == 'id' and t[1] == 'nil':
        g.next()
        return None
    if t[0] == 'num':
        g.next()
        return float(t[1]) if '.' in t[1] else int(t[1], 0)
    g.fail(t, 'valor que el lector de la tabla no sabe evaluar')


def resolve(typ, ctx):
    while typ and typ[0] == 'named' and typ[1] in ctx['aliases']:
        typ = ctx['aliases'][typ[1]]
    return typ


def go_composite(g, typ, ctx):
    typ = resolve(typ, ctx)
    g.expect('{')
    kind = typ[0] if typ else None
    if kind == 'named':
        out = OrderedDict([('_type', typ[1])])
        while g.peek()[1] != '}':
            key = g.next()
            if key[0] != 'id':
                g.fail(key, 'esperaba el nombre de un campo')
            g.expect(':')
            out[key[1]] = go_value(g, None, ctx)
            if g.peek()[1] == ',':
                g.next()
            elif g.peek()[1] != '}':
                g.fail(g.peek(), 'esperaba «,» o «}»')
        g.next()
        return out
    if kind in ('slice', 'array'):
        items = []
        while g.peek()[1] != '}':
            items.append(go_value(g, typ[-1], ctx))
            if g.peek()[1] == ',':
                g.next()
            elif g.peek()[1] != '}':
                g.fail(g.peek(), 'esperaba «,» o «}»')
        g.next()
        return items
    if kind == 'map':
        out = OrderedDict()
        while g.peek()[1] != '}':
            k = go_value(g, typ[1], ctx)
            g.expect(':')
            out[k] = go_value(g, typ[2], ctx)
            if g.peek()[1] == ',':
                g.next()
            elif g.peek()[1] != '}':
                g.fail(g.peek(), 'esperaba «,» o «}»')
        g.next()
        return out
    g.fail(g.peek(), f'literal de un tipo que la tabla no usa ({typ})')


def mentions(typ, names, ctx):
    typ = resolve(typ, ctx)
    if not typ:
        return False
    if typ[0] == 'named':
        return typ[1] in names
    return any(isinstance(x, tuple) and mentions(x, names, ctx) for x in typ[1:])


def read_var_spec(g, entry_types, ctx, entries):
    """Una especificación de `var`. Si su valor es un literal compuesto de un
    tipo que contiene entradas (map[string]Provider, []Entry…), se lee ENTERO
    y en estricto: lo que no sepa evaluar falla, no se salta. Lo demás se salta."""
    name = g.next()
    if name[0] != 'id':
        g.fail(name, 'esperaba el nombre de una variable')
    if g.peek(skip_nl=False)[1] == ',':
        g.skip_statement()
        return
    if g.peek(skip_nl=False)[1] != '=':
        if g.peek(skip_nl=False)[0] == 'nl':
            return
        g.parse_type()
        if g.peek(skip_nl=False)[1] != '=':
            g.skip_statement()
            return
    g.next()
    start = g.i
    lit_type = None
    if g.peek()[0] == 'id' or g.peek()[1] in ('[', '*'):
        try:
            lit_type = g.parse_type()
        except GoParseError:
            lit_type = None
    if lit_type is not None and g.peek(skip_nl=False)[1] == '{' and mentions(lit_type, entry_types, ctx):
        value = go_composite(g, lit_type, ctx)
        rows = value.items() if isinstance(value, dict) else ((None, v) for v in value)
        for key, v in rows:
            if not isinstance(v, dict) or v.get('_type') not in entry_types:
                g.fail(name, f'«var {name[1]}» mezcla filas que no son entradas')
            v = OrderedDict(v)
            v['_var'] = name[1]
            if key is not None:
                v['_mapkey'] = key
            v['_file'] = g.path
            entries.append(v)
        return
    g.i = start
    g.skip_statement()


def read_catalog():
    base = os.path.join(ROOT, CATALOG_DIR)
    if not os.path.isdir(base):
        raise SourceError(f'falta {CATALOG_DIR}/ — la tabla que lee `nucleus add` al pin')
    files = []
    for name in sorted(os.listdir(base)):
        if name.endswith('.go') and not name.endswith('_test.go'):
            files.append(GoFile(f'{CATALOG_DIR}/{name}', rd(f'{CATALOG_DIR}/{name}')))
    if not files:
        raise SourceError(f'{CATALOG_DIR}/ no tiene ficheros Go')
    consts, structs, aliases = go_scan(files)
    entry_types = {n for n, f in structs.items() if 'Name' in f and 'Module' in f}
    entry_types |= {n for n, a in aliases.items() if a[0] == 'named' and a[1] in entry_types}
    if not entry_types:
        raise SourceError(f'{CATALOG_DIR}: ningún struct con Name y Module — la tabla cambió de forma')
    ctx = {'consts': consts, 'aliases': aliases}
    entries = []
    for g in files:
        g.i = 0
        while g.peek()[0] != 'eof':
            t = g.next()
            if t[0] == 'id' and t[1] == 'func':
                while g.peek()[1] != '{' and g.peek()[0] != 'eof':
                    if g.peek()[1] in '([':
                        g.skip_balanced()
                    else:
                        g.next()
                if g.peek()[1] == '{':
                    g.skip_balanced()
                continue
            if not (t[0] == 'id' and t[1] == 'var'):
                continue
            if g.peek()[1] != '(':
                read_var_spec(g, entry_types, ctx, entries)
                continue
            g.next()
            while True:
                while g.peek(skip_nl=False)[0] == 'nl':
                    g.next(skip_nl=False)
                if g.peek()[1] == ')':
                    g.next()
                    break
                if g.peek()[0] == 'eof':
                    g.fail(g.peek(), 'bloque var sin cerrar')
                read_var_spec(g, entry_types, ctx, entries)
    if not entries:
        raise SourceError(f'{CATALOG_DIR}: la tabla no tiene ninguna entrada')
    return entries


GROUP_ORDER = ['database drivers', 'telemetry exporters', 'storage providers',
               'authentication backends', 'secrets resolvers']
SHIPS_TEXT = {
    'module': ('a module of the nucleus repository, published on its own so that an application '
               'links only what it uses: `nucleus add <name>` fetches it and writes the blank '
               'import that registers it'),
    'core': ('part of the framework module itself: there is nothing to fetch, and '
             '`nucleus add <name>` writes the wiring'),
    'suite': ('a sibling product of the suite (the admin panel, the ORM and the bridges between '
              'them): `nucleus new --with <name>` adds it to a new project'),
}


def plural(kind):
    if kind.endswith('s'):
        return kind
    if re.search(r'[^aeiou]y$', kind):
        return kind[:-1] + 'ies'
    return kind + 's'


def catalog_rows(entries, pin):
    nucleus_root = f'{OWNER}/nucleus'
    rows, seen = [], set()
    for e in entries:
        name, module = e.get('Name'), e.get('Module')
        if not name or not module:
            raise SourceError(f"{e['_file']}: una entrada de «{e['_var']}» sin Name o sin Module")
        if name in seen:
            raise SourceError(f'{CATALOG_DIR}: el nombre «{name}» está dos veces en la tabla')
        seen.add(name)
        ships = e.get('Ships')
        if not ships:
            if module == nucleus_root:
                ships = 'core'
            elif module.startswith(nucleus_root + '/'):
                ships = 'module'
            else:
                ships = 'suite'
        group = e.get('Group') or ('suite products' if ships == 'suite' else plural(e.get('Kind') or 'other'))
        version = module_version(module, pin)
        if version is None:
            raise SourceError(f'la tabla de `nucleus add` instala {module} ({name}) y el set no lo certifica '
                              '(versions.yaml): una página que lo publicara prometería un módulo fuera del set')
        rows.append({'name': name, 'ships': ships, 'group': group, 'module': module, 'version': version,
                     'entry': e})
    order = {g: i for i, g in enumerate(GROUP_ORDER)}
    groups = []
    for r in rows:
        if r['group'] not in groups:
            groups.append(r['group'])
    first = list(groups)
    groups.sort(key=lambda g: (g == 'suite products', order.get(g, len(order)), first.index(g)))
    return rows, groups


def module_version(module, pin):
    for repo in REPOS:
        root = f'{OWNER}/{repo}'
        if module == root:
            return pin['modules'][repo]
        if module.startswith(root + '/'):
            return pin[repo].get(module.rsplit('/', 1)[-1])
    return None


