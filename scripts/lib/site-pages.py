FAMILIES = ('api', 'catalog', 'releases')


def generate(families, pin):
    pages, owned, notes = OrderedDict(), [], {}
    if 'api' in families:
        for spec in API:
            pages[f"{REF_DIR}/api-{spec['repo']}.md"] = render_api(spec, pin)
        owned.append((REF_DIR, re.compile(r'^api-.*\.mdx?$')))
    if 'catalog' in families:
        pages[f'{REF_DIR}/catalog.md'] = render_catalog(pin)
        owned.append((REF_DIR, re.compile(r'^catalog\.mdx?$')))
    if 'releases' in families:
        posts, sets = render_posts()
        pages.update(posts)
        owned.append((POSTS_DIR, re.compile(r'.*')))
        notes['latest'] = sets[-1][0]
    if 'api' in families and 'catalog' in families:
        # el directorio entero es del generador: nada a mano dentro
        owned.append((REF_DIR, re.compile(r'.*')))
    return pages, owned, notes


def on_disk(owned):
    found = set()
    for d, pat in owned:
        full = os.path.join(ROOT, d)
        if not os.path.isdir(full):
            continue
        for name in os.listdir(full):
            if pat.match(name) and os.path.isfile(os.path.join(full, name)):
                found.add(f'{d}/{name}')
    return found


def main(argv):
    check = False
    families = []
    for a in argv:
        if a == '--check':
            check = True
        elif a in FAMILIES:
            families.append(a)
        elif a in ('-h', '--help'):
            print(__doc__)
            return 0
        else:
            print(f'site-pages: argumento desconocido «{a}» (--check, {"|".join(FAMILIES)})', file=sys.stderr)
            return 2
    families = families or list(FAMILIES)
    try:
        pin = manifest(rd('versions.yaml'), 'versions.yaml')
        pages, owned, notes = generate(families, pin)
    except SourceError as e:
        print(f'FAIL: generated-pages — {e}', file=sys.stderr)
        return 1
    existing = on_disk(owned)

    if not check:
        for rel, text in pages.items():
            path = os.path.join(ROOT, rel)
            os.makedirs(os.path.dirname(path), exist_ok=True)
            old = open(path, encoding='utf-8').read() if os.path.exists(path) else None
            if old != text:
                with open(path, 'w', encoding='utf-8') as f:
                    f.write(text)
                print(f'escrito  {rel}')
        for rel in sorted(existing - set(pages)):
            os.remove(os.path.join(ROOT, rel))
            print(f'borrado  {rel} (ya no corresponde a nada del pin)')
        print(f'OK: generated-pages — {len(pages)} páginas al día ({", ".join(families)})')
        return 0

    fails = []
    latest = notes.get('latest')
    for rel, text in pages.items():
        path = os.path.join(ROOT, rel)
        if not os.path.exists(path):
            if latest and rel == f'{POSTS_DIR}/{post_name(latest)}.md':
                fails.append(f'[releases] Quantum {latest}, el set que declara versions.yaml, no tiene post '
                             f'({rel}): el tren lo escribe en el PR de set (bump-set.sh corre este generador; '
                             'a mano: python3 scripts/lib/site-pages.py)')
            else:
                fails.append(f'[{family_of(rel)}] falta {rel}: el pin la genera y el sitio no la publica')
            continue
        old = open(path, encoding='utf-8').read()
        if old != text:
            diff = list(difflib.unified_diff(old.splitlines(), text.splitlines(), 'publicado', 'al pin',
                                             lineterm='', n=0))
            shown = [d for d in diff if not d.startswith(('---', '+++'))][:8]
            fails.append(f'[{family_of(rel)}] {rel} no es lo que el pin genera '
                         f'({sum(1 for d in diff if d[:1] in "+-" and not d.startswith(("---", "+++")))} líneas difieren):\n'
                         + '\n'.join('    ' + d for d in shown))
    for rel in sorted(existing - set(pages)):
        fails.append(f'[{family_of(rel)}] {rel} sobra: el directorio es del generador y nada del pin la produce '
                     '(una página a mano va en website/docs/)')
    if fails:
        for f in fails:
            print(f'FAIL: generated-pages — {f}', file=sys.stderr)
        print('generated-pages: el sitio publica algo que el pin no da. Regenera con '
              'python3 scripts/lib/site-pages.py y commitea el resultado; no se editan a mano.', file=sys.stderr)
        return 1
    print(f'OK: generated-pages — {len(pages)} páginas iguales a lo que genera el pin ({", ".join(families)})'
          + (f'; el último set, Quantum {latest}, tiene su post' if latest else ''))
    return 0


def family_of(rel):
    if rel.startswith(POSTS_DIR):
        return 'releases'
    return 'catalog' if os.path.basename(rel).startswith('catalog') else 'api'


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
