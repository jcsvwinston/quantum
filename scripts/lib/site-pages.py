def product_modules(repo, pin):
    """{ruta de módulo: versión del set} de todo go.mod publicado del producto."""
    base = os.path.join(ROOT, repo)
    if not os.path.isdir(base):
        raise SourceError(f'falta el submódulo {repo}/')
    found = {}
    for dirpath, dirnames, filenames in os.walk(base):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
        if 'go.mod' not in filenames:
            continue
        with open(os.path.join(dirpath, 'go.mod'), encoding='utf-8') as f:
            m = re.search(r'^module\s+(\S+)', f.read(), re.M)
        if not m:
            continue
        rel = os.path.relpath(dirpath, base).replace(os.sep, '/')
        if rel == '.':
            found[m.group(1)] = pin['modules'][repo]
        else:
            ver = pin[repo].get(rel.split('/')[-1])
            if ver:
                found[m.group(1)] = ver
    root = f'{OWNER}/{repo}'
    if root not in found:
        raise SourceError(f'{repo}/go.mod no declara el módulo {root}')
    return found


def module_of(pkg, modules):
    best = None
    for mod in modules:
        if pkg == mod or pkg.startswith(mod + '/'):
            if best is None or len(mod) > len(best):
                best = mod
    return best


