def manifest(text, where):
    """quantum, released y los cuatro bloques de versiones de un versions.yaml."""
    def scalar(key):
        m = re.search(rf'^{key}:[ \t]*"?([^"#\n]+?)"?[ \t]*(?:#.*)?$', text, re.M)
        return m.group(1).strip() if m else None

    def block(name):
        out = OrderedDict()
        lines = text.split('\n')
        try:
            i = lines.index(f'{name}:')
        except ValueError:
            return out
        for line in lines[i + 1:]:
            if line.strip() == '' or line.lstrip().startswith('#'):
                continue
            if not line[0].isspace():
                break
            m = re.match(r'^\s+([A-Za-z0-9_-]+):\s*"([^"]+)"', line)
            if m:
                out[m.group(1)] = m.group(2)
        return out

    m = {'quantum': scalar('quantum'), 'released': scalar('released'),
         'modules': block('modules')}
    for repo in REPOS:
        m[repo] = block(f'{repo}_modules')
    if not m['quantum'] or not re.match(r'^\d+\.\d+\.\d+$', m['quantum']):
        raise SourceError(f'{where}: no declara «quantum:» con una versión X.Y.Z')
    if not m['released'] or not re.match(r'^\d{4}-\d{2}-\d{2}$', m['released']):
        raise SourceError(f'{where}: no declara «released:» con una fecha AAAA-MM-DD')
    for repo in REPOS:
        if not m['modules'].get(repo):
            raise SourceError(f'{where}: el bloque modules no fija {repo}')
    return m


def semver(v):
    return tuple(int(x) for x in v.lstrip('v').split('-')[0].split('.'))


def change(old, new):
    if old is None and new is None:
        return '—'
    if old is None:
        return 'new'
    if new is None:
        return 'removed'
    a, b = semver(old), semver(new)
    if a == b:
        return '—'
    if b < a:
        return 'downgrade'
    if b[0] != a[0]:
        return 'major'
    if b[1] != a[1]:
        return 'minor'
    return 'patch'


