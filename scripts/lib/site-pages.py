def new_pkg():
    return {'types': OrderedDict(), 'func': [], 'const': [], 'var': []}


def type_entry(pkg, name):
    t = pkg['types'].get(name)
    if t is None:
        t = {'sig': None, 'alias_of': None, 'interface': False, 'fields': [], 'methods': []}
        pkg['types'][name] = t
    return t


def read_surface(spec):
    """{paquete: estructura} desde el fichero congelado del producto."""
    text = rd(f"{spec['repo']}/{spec['source']}")
    pkgs = OrderedDict()
    n = 0
    if spec['format'] == 'baseline':
        for i, line in enumerate(text.splitlines(), 1):
            line = line.strip()
            if not line or line.startswith('#'):
                continue
            m = re.match(r'^(\S+)\s+([a-z-]+):(\S+)$', line)
            if not m:
                raise SourceError(f"{spec['repo']}/{spec['source']}:{i}: línea con forma desconocida «{line}»")
            pkg, kind, name = m.groups()
            p = pkgs.setdefault(pkg, new_pkg())
            n += 1
            if kind in ('method', 'field', 'iface-method'):
                typ, _, member = name.partition('.')
                if not member:
                    raise SourceError(f"{spec['repo']}/{spec['source']}:{i}: «{kind}:{name}» sin tipo")
                t = type_entry(p, typ)
                t['fields' if kind == 'field' else 'methods'].append((member, None))
                if kind == 'iface-method':
                    t['interface'] = True
            elif kind == 'type':
                type_entry(p, name)
            elif kind in ('func', 'const', 'var'):
                p[kind].append((name, None))
            else:
                raise SourceError(f"{spec['repo']}/{spec['source']}:{i}: clase de símbolo desconocida «{kind}»")
    else:
        try:
            symbols = json.loads(text)['symbols']
        except (ValueError, KeyError) as e:
            raise SourceError(f"{spec['repo']}/{spec['source']}: no es un inventario de símbolos ({e})")
        for s in symbols:
            pkg, kind, name = s.get('pkg'), s.get('kind'), s.get('name')
            if not (pkg and kind and name):
                raise SourceError(f"{spec['repo']}/{spec['source']}: símbolo sin pkg/kind/name: {s}")
            p = pkgs.setdefault(pkg, new_pkg())
            n += 1
            sig = s.get('sig')
            if kind in ('method', 'field'):
                m = re.match(r'^\(\*?([A-Za-z_]\w*)(?:\[[^\]]*\])?\)\.(\w+)$', name) or \
                    re.match(r'^([A-Za-z_]\w*)\.(\w+)$', name)
                if not m:
                    raise SourceError(f"{spec['repo']}/{spec['source']}: «{kind}» con nombre desconocido «{name}»")
                t = type_entry(p, m.group(1))
                t['fields' if kind == 'field' else 'methods'].append((m.group(2), sig))
            elif kind == 'type':
                t = type_entry(p, name)
                t['sig'] = sig
                t['alias_of'] = s.get('alias_of')
                if sig == 'interface':
                    t['interface'] = True
            elif kind in ('func', 'const', 'var'):
                p[kind].append((name, sig))
            else:
                raise SourceError(f"{spec['repo']}/{spec['source']}: clase de símbolo desconocida «{kind}»")
    if n == 0:
        raise SourceError(f"{spec['repo']}/{spec['source']}: cero símbolos — una página vacía no es una referencia")
    return pkgs, n


def short_alias(target, pkg):
    """quarkdriver.Check para el alias de otro paquete; el nombre solo si es el mismo."""
    path, _, name = target.rpartition('.')
    if path == pkg:
        return name
    return f"{path.rsplit('/', 1)[-1]}.{name}"


def member_list(members):
    if any(sig for _, sig in members):
        return None
    return ', '.join(code(m) for m, _ in members)


def render_api(spec, pin):
    repo = spec['repo']
    title = TITLES[repo]
    tag = pin['modules'][repo]
    suite = pin['quantum']
    pkgs, total = read_surface(spec)
    modules = product_modules(repo, pin)
    root_mod = f'{OWNER}/{repo}'

    def display(pkg):
        if pkg == root_mod:
            return repo
        return pkg[len(root_mod) + 1:] if pkg.startswith(root_mod + '/') else pkg

    def heading(pkg):
        return code(display(pkg)) + (' (module root)' if pkg == root_mod else '')

    for p in pkgs.values():
        p['types'] = OrderedDict(sorted(p['types'].items()))
        for t in p['types'].values():
            t['fields'].sort()
            t['methods'].sort()
        for kind in ('func', 'const', 'var'):
            p[kind].sort()

    counts = []
    for pkg, p in pkgs.items():
        c = {'types': len(p['types']),
             'functions': len(p['func']),
             'methods': sum(len(t['methods']) for t in p['types'].values()),
             'fields': sum(len(t['fields']) for t in p['types'].values()),
             'constants': len(p['const']),
             'variables': len(p['var'])}
        counts.append((pkg, c))
    columns = [k for k in ('types', 'functions', 'methods', 'fields', 'constants', 'variables')
               if any(c[k] for _, c in counts)]

    src_link = f"{GH}/{repo}/blob/{tag}/{spec['source']}"
    out = [front([
        ('title', f'{title} API surface'),
        ('sidebar_label', title),
        ('description', f'The exported Go API of {title} {tag} that its CI keeps frozen, '
                        f'generated from the file it compares the code with, at the version '
                        f'Quantum {suite} certifies.'),
        ('custom_edit_url', None),
    ]), '', MARK, '', f'# {title} API surface', '']
    out.append(
        f'The public Go API of **{title} {tag}**, the version Quantum {suite} certifies: '
        f'**{num(total)}** exported symbols in **{num(len(pkgs))}** packages. {title} keeps '
        f'this list in [`{spec["source"]}`]({src_link}). {spec["how"]} Removing an exported '
        f'symbol is a breaking change, and the suite ships breaking changes only in a major '
        f'version. This page is generated from that file at the pinned version, so it lists '
        f'exactly what the check protects.')
    out.append('')
    out.append('Each package links to its documentation on pkg.go.dev at this version, where '
               'every symbol has its signature and its comment.')
    out.append('')
    out.append('| Package | ' + ' | '.join(c.capitalize() for c in columns) + ' |')
    out.append('|---|' + '---:|' * len(columns))
    for pkg, c in counts:
        out.append(f'| [{heading(pkg)}](#{slug(display(pkg))}) | '
                   + ' | '.join(num(c[k]) if c[k] else '' for k in columns) + ' |')
    out.append('')

    for pkg, p in pkgs.items():
        mod = module_of(pkg, modules)
        if mod is None:
            raise SourceError(f'{repo}: el paquete {pkg} no pertenece a ningún módulo que el set certifique')
        sub = pkg[len(mod):]
        n_pkg = (len(p['types']) + len(p['func']) + len(p['const']) + len(p['var'])
                 + sum(len(t['methods']) + len(t['fields']) for t in p['types'].values()))
        out.append(f'## {heading(pkg)} {{#{slug(display(pkg))}}}')
        out.append('')
        out.append(f'`{pkg}` · {num(n_pkg)} symbols · '
                   f'[pkg.go.dev](https://pkg.go.dev/{mod}@{modules[mod]}{sub})')
        out.append('')
        if p['types']:
            out.append('**Types**')
            out.append('')
            for name, t in p['types'].items():
                head = f'- {code(name)}'
                if t['alias_of']:
                    head += f' = {code(short_alias(t["alias_of"], pkg))} (alias)'
                elif t['sig']:
                    head += f' {code(t["sig"])}'
                elif t['interface']:
                    head += ' interface'
                parts = []
                nested = []
                for label, key in (('fields', 'fields'), ('methods', 'methods')):
                    members = t[key]
                    if not members:
                        continue
                    flat = member_list(members)
                    if flat is not None:
                        parts.append(f'{label} {flat}')
                    else:
                        nested.extend(f'  - {code(m)}' + (f' {code(s)}' if s else '') for m, s in members)
                if parts:
                    head += ' — ' + '; '.join(parts)
                out.append(head)
                out.extend(nested)
            out.append('')
        for kind, label in (('func', 'Functions'), ('const', 'Constants'), ('var', 'Variables')):
            items = p[kind]
            if not items:
                continue
            flat = member_list(items)
            if flat is not None:
                out.append(f'**{label}** — {flat}')
            else:
                out.append(f'**{label}**')
                out.append('')
                out.extend(f'- {code(m)}' + (f' {code(s)}' if s else '') for m, s in items)
            out.append('')

    if spec.get('extension'):
        ext = [l.strip() for l in rd(f"{repo}/{spec['extension']}").splitlines()
               if l.strip() and not l.strip().startswith('#')]
        if not ext:
            raise SourceError(f"{repo}/{spec['extension']}: cero campos")
        ext_link = f"{GH}/{repo}/blob/{tag}/{spec['extension']}"
        out.append('## Fields an extension may rely on {#extension-surface}')
        out.append('')
        out.append(f'An `app.Extension` receives the whole `*app.App`. These are the **{num(len(ext))}** '
                   f'fields of `App` that {title} freezes for extensions, kept in '
                   f'[`{spec["extension"]}`]({ext_link}) and compared with the code by the same '
                   f'CI: removing one, or adding one without listing it, fails the build.')
        out.append('')
        out.extend(f'- {code(f)}' for f in ext)
        out.append('')
    return '\n'.join(out).rstrip('\n') + '\n'


