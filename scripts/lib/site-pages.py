def git(*args):
    r = subprocess.run(['git', '-C', ROOT] + list(args), capture_output=True, text=True)
    if r.returncode != 0:
        raise SourceError(f'git {" ".join(args)}: {r.stderr.strip() or "falló"}')
    return r.stdout


def certified_sets():
    """[(versión, manifiesto, tag o None)] en orden de versión."""
    tags = [t for t in git('tag', '--list', 'v*').split()
            if re.match(r'^v\d+\.\d+\.\d+$', t) and semver(t)[0] >= 1]
    if not tags:
        raise SourceError('el paraguas no tiene ningún tag de suite vX.Y.Z: sin historia no hay posts que '
                          'comparar (en CI, el checkout necesita fetch-depth: 0 para traer los tags)')
    sets = []
    for t in tags:
        m = manifest(git('show', f'{t}:versions.yaml'), f'versions.yaml en {t}')
        if m['quantum'] != t[1:]:
            raise SourceError(f'el tag {t} declara la suite {m["quantum"]} en su versions.yaml')
        sets.append((m['quantum'], m, t))
    current = manifest(rd('versions.yaml'), 'versions.yaml')
    if current['quantum'] not in {v for v, _, _ in sets}:
        if semver(current['quantum']) < max(semver(v) for v, _, _ in sets):
            raise SourceError(f'versions.yaml declara {current["quantum"]}, por debajo del último tag de suite')
        sets.append((current['quantum'], current, None))
    sets.sort(key=lambda s: semver(s[0]))
    return sets


def post_name(ver):
    return f'quantum-{ver.replace(".", "-")}'


def join_words(items):
    if len(items) <= 1:
        return ''.join(items)
    return ', '.join(items[:-1]) + ' and ' + items[-1]


def render_post(ver, m, prev, hour):
    pillars = [(r, m['modules'][r]) for r in REPOS]
    n_sib = sum(len(m[r]) for r in REPOS)
    pin_words = join_words([f'**{r} {v}**' for r, v in pillars])
    out = [front([
        ('title', f'Quantum {ver}'),
        ('description', f'Quantum {ver} certifies ' + join_words([f'{r} {v}' for r, v in pillars]) + '.'),
        ('date', f"{m['released']}T{hour:02d}:00:00Z"),
        ('slug', post_name(ver)),
        ('hide_table_of_contents', True),
    ]), '', MARK, '']
    lead = f'Quantum {ver} was certified on {m["released"]}. It pins {pin_words}'
    lead += f', with {num(n_sib)} sibling modules.' if n_sib else '.'
    out.append(lead)
    out.append('')
    if prev is None:
        out.append('It is the first set with a suite tag: the sets before it were recorded only as '
                   'commits of the manifest.')
    else:
        pver, pm = prev
        kind = change(pver, ver)
        moves, stays = [], []
        for r, v in pillars:
            old = pm['modules'][r]
            c = change(old, v)
            (stays if c == '—' else moves).append(
                f'{r} stays at {v}' if c == '—' else f'{r} goes from {old} to {v} ({c})')
        sentence = f'A {kind} release of the suite after Quantum {pver}: ' if kind in ('major', 'minor', 'patch') \
            else f'After Quantum {pver}: '
        sentence += join_words(moves + stays) + '.'
        moved = sum(1 for r in REPOS for k, v in m[r].items() if change(pm[r].get(k), v) != '—')
        moved += sum(1 for r in REPOS for k in pm[r] if k not in m[r])
        if n_sib or moved:
            sentence += (f' {num(moved)} sibling module{"s" if moved != 1 else ""} '
                         f'{"change" if moved != 1 else "changes"} version.' if moved
                         else ' No sibling module changes version.')
        out.append(sentence)
    out.append('')
    out.append('<!-- truncate -->')
    out.append('')
    out.append('## The products')
    out.append('')
    if prev is None:
        out.append(f'| Product | Quantum {ver} | Release notes |')
        out.append('|---|---|---|')
        for r, v in pillars:
            out.append(f'| {TITLES[r]} | {v} | [{v}]({GH}/{r}/releases/tag/{v}) · [all versions]({RELEASE_NOTES[r]}) |')
    else:
        pver, pm = prev
        out.append(f'| Product | Quantum {pver} | Quantum {ver} | Change | Release notes |')
        out.append('|---|---|---|---|---|')
        for r, v in pillars:
            old = pm['modules'][r]
            c = change(old, v)
            notes = (f'[changes]({GH}/{r}/compare/{old}...{v}) · [{v}]({GH}/{r}/releases/tag/{v}) · '
                     if c != '—' else '')
            out.append(f'| {TITLES[r]} | {old} | {v} | {c} | {notes}[all versions]({RELEASE_NOTES[r]}) |')
    out.append('')
    if n_sib or (prev is not None and any(prev[1][r] for r in REPOS)):
        out.append('## Sibling modules')
        out.append('')
        out.append('Each product publishes its optional pieces as modules of their own; a module is '
                   'named here by the last segment of its path, as in the manifest '
                   '([how keys map to paths](/start/certified-sets)).')
        out.append('')
        if prev is None:
            out.append('| Repository | Module | Version |')
            out.append('|---|---|---|')
        else:
            out.append(f'| Repository | Module | Version | Since {prev[0]} |')
            out.append('|---|---|---|---|')
        for r in REPOS:
            keys = list(m[r])
            if prev is not None:
                keys += [k for k in prev[1][r] if k not in m[r]]
            for k in sorted(keys):
                v = m[r].get(k)
                if prev is None:
                    out.append(f'| {r} | {code(k)} | {v} |')
                else:
                    out.append(f'| {r} | {code(k)} | {v or "—"} | {change(prev[1][r].get(k), v)} |')
        out.append('')
    out.append('## The manifest')
    out.append('')
    out.append(f'- The manifest of this set: [`versions.yaml` at v{ver}]({GH}/quantum/blob/v{ver}/versions.yaml). '
               'Its `notes:` field tells the story of the set, in Spanish, the working language of the '
               'project.')
    if semver(ver) >= BUNDLE_SINCE:
        out.append(f'- Its signed bundle (the manifest, the `require` block and their checksums): '
                   f'[GitHub release v{ver}]({GH}/quantum/releases/tag/v{ver}), and '
                   f'[how to verify it](/start/verifying-a-set).')
    else:
        out.append('- Sets before Quantum 1.30.0 have no signed bundle.')
    return '\n'.join(out).rstrip('\n') + '\n'


def render_posts():
    sets = certified_sets()
    pages, per_day, prev = OrderedDict(), {}, None
    for ver, m, _tag in sets:
        hour = per_day.get(m['released'], 0)
        if hour > 23:
            raise SourceError(f'más de 24 sets el {m["released"]}: el orden del blog por hora no alcanza')
        per_day[m['released']] = hour + 1
        pages[f'{POSTS_DIR}/{post_name(ver)}.md'] = render_post(ver, m, prev, hour)
        prev = (ver, m)
    return pages, sets


